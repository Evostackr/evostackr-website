/**
 * Tier 4 — Real-World Application Scenarios & Production Invariants
 * 
 * Tests full production build (npm run build), static oxlint linting,
 * formal Schema.org compliance, RSS RFC 822 compliance, sitemap XML
 * validation, and zero CLS image styling.
 */

import { execSync } from 'node:child_process';
import {
  assert,
  readProjectFile,
  projectFileExists,
  importProjectModule,
  parseAndValidateXml,
  isValidRfc822Date,
  validateSchemaOrgBlogPosting,
  validateSchemaOrgBreadcrumbList,
  PROJECT_ROOT
} from './utils/test-helpers.mjs';

export async function runTier4Tests() {
  const results = [];

  async function test(name, fn) {
    const start = Date.now();
    try {
      await fn();
      results.push({ name, tier: 4, passed: true, duration: Date.now() - start });
    } catch (err) {
      results.push({
        name,
        tier: 4,
        passed: false,
        duration: Date.now() - start,
        error: err.message,
        stack: err.stack
      });
    }
  }

  // --- Test 1: Production TypeScript & Vite Build (R5 / F14) ---
  await test('TC-F14-01: Production build clean execution (npm run build)', () => {
    try {
      execSync('npm run build', {
        cwd: PROJECT_ROOT,
        encoding: 'utf-8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 60000
      });
      assert(
        projectFileExists('dist/index.html'),
        'Build output dist/index.html must exist after npm run build'
      );
    } catch (err) {
      const errorOutput = err.stderr || err.stdout || err.message;
      throw new Error(`npm run build failed with exit code ${err.status}:\n${errorOutput}`);
    }
  });

  // --- Test 2: Static Oxlint Verification (R5 / F14) ---
  await test('TC-F14-02: Static Oxlint verification (npx oxlint src)', () => {
    try {
      execSync('npx oxlint src', {
        cwd: PROJECT_ROOT,
        encoding: 'utf-8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 30000
      });
      // Exit code 0 means 0 errors and 0 warnings
    } catch (err) {
      const errorOutput = err.stderr || err.stdout || err.message;
      throw new Error(`npx oxlint src failed:\n${errorOutput}`);
    }
  });

  // --- Test 3: Schema.org Validator Compliance (R4 / F11) ---
  await test('TC-F11-02: Formal Schema.org BlogPosting & BreadcrumbList compliance', async () => {
    assert(projectFileExists('src/data/blogArticles.ts'), 'src/data/blogArticles.ts must exist');
    const blogModule = await importProjectModule('src/data/blogArticles.ts');
    const articles = blogModule.getAllArticles();
    const baseUrl = 'https://evostackr.in';

    articles.forEach(article => {
      // Simulate BlogPosting JSON-LD generated by SEOHead
      const blogPostingSchema = {
        '@context': 'https://schema.org',
        '@type': 'BlogPosting',
        '@id': `${baseUrl}/blog/${article.slug}#article`,
        mainEntityOfPage: {
          '@type': 'WebPage',
          '@id': `${baseUrl}/blog/${article.slug}`
        },
        headline: article.headline || article.title,
        description: article.excerpt,
        image: [
          `${baseUrl}${article.featuredImage.url.startsWith('/') ? '' : '/'}${article.featuredImage.url}`,
          ...article.contextualImages.map(
            img => `${baseUrl}${img.url.startsWith('/') ? '' : '/'}${img.url}`
          )
        ],
        datePublished: article.publishedDate,
        dateModified: article.modifiedDate,
        author: {
          '@type': 'Person',
          name: article.author.name,
          jobTitle: article.author.role
        },
        publisher: {
          '@type': 'Organization',
          name: 'Evostackr',
          url: baseUrl,
          logo: {
            '@type': 'ImageObject',
            url: `${baseUrl}/evostackr-logo.png`
          }
        },
        keywords: article.tags ? article.tags.join(', ') : '',
        wordCount: article.wordCount,
        articleSection: article.categoryName
      };

      validateSchemaOrgBlogPosting(blogPostingSchema, `BlogPosting[${article.slug}]`);

      // Simulate BreadcrumbList JSON-LD
      const breadcrumbSchema = {
        '@context': 'https://schema.org',
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Home', item: `${baseUrl}/` },
          { '@type': 'ListItem', position: 2, name: 'Blog', item: `${baseUrl}/blog` },
          {
            '@type': 'ListItem',
            position: 3,
            name: article.categoryName,
            item: `${baseUrl}/blog/category/${article.categorySlug}`
          },
          {
            '@type': 'ListItem',
            position: 4,
            name: article.title,
            item: `${baseUrl}/blog/${article.slug}`
          }
        ]
      };

      validateSchemaOrgBreadcrumbList(breadcrumbSchema, `BreadcrumbList[${article.slug}]`);
    });
  });

  // --- Test 4: RSS RFC 822 Date Compliance (R4 / F12) ---
  await test('TC-F12-02: RSS 2.0 RFC 822 pubDate compliance', () => {
    const rssContent = readProjectFile('public/rss.xml');
    const parsedRss = parseAndValidateXml(rssContent, 'public/rss.xml');
    const pubDates = parsedRss.extractTagValues('pubDate');

    assert(pubDates.length > 0, 'public/rss.xml must contain at least one <pubDate>');

    pubDates.forEach((pubDate, idx) => {
      assert(
        isValidRfc822Date(pubDate),
        `public/rss.xml item[${idx}] <pubDate> "${pubDate}" is not RFC 822 compliant (e.g. "Sat, 24 Oct 2026 12:00:00 GMT")`
      );
    });
  });

  // --- Test 5: Sitemap XML Validity & Google Image Namespaces (R4 / F12) ---
  await test('TC-F12-03: Sitemap XML well-formedness and Google Image extension syntax', () => {
    const sitemapContent = readProjectFile('public/sitemap.xml');
    const parsedSitemap = parseAndValidateXml(sitemapContent, 'public/sitemap.xml');

    assert(
      sitemapContent.includes('xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"'),
      'public/sitemap.xml must declare xmlns:image namespace'
    );

    const imageLocs = parsedSitemap.extractTagValues('image:loc');
    assert(imageLocs.length >= 7, 'public/sitemap.xml must contain <image:loc> entries');
    imageLocs.forEach((loc, idx) => {
      assert(loc.startsWith('https://'), `image:loc[${idx}] "${loc}" must be an absolute HTTPS URL`);
    });
  });

  // --- Test 6: Zero Cumulative Layout Shift (CLS) Invariants (R5 / F7, F13) ---
  await test('TC-F7-02: Zero Cumulative Layout Shift (CLS) image styling and dimensions', async () => {
    // 1. Data layer: explicit dimensions
    if (projectFileExists('src/data/blogArticles.ts')) {
      const blogModule = await importProjectModule('src/data/blogArticles.ts');
      const articles = blogModule.getAllArticles();

      articles.forEach(article => {
        assert(
          typeof article.featuredImage.width === 'number' && article.featuredImage.width > 0,
          `Article ${article.slug}: featuredImage.width must be positive number`
        );
        assert(
          typeof article.featuredImage.height === 'number' && article.featuredImage.height > 0,
          `Article ${article.slug}: featuredImage.height must be positive number`
        );

        article.contextualImages.forEach((img, i) => {
          assert(
            typeof img.width === 'number' && img.width > 0,
            `Article ${article.slug} contextualImages[${i}].width must be positive number`
          );
          assert(
            typeof img.height === 'number' && img.height > 0,
            `Article ${article.slug} contextualImages[${i}].height must be positive number`
          );
        });
      });
    }

    // 2. CSS layer: aspect-ratio: 16 / 9 for zero layout shift
    if (projectFileExists('src/views/BlogArticle.css')) {
      const articleCss = readProjectFile('src/views/BlogArticle.css');
      assert(
        articleCss.includes('aspect-ratio: 16 / 9') ||
        articleCss.includes('aspect-ratio: 16/9') ||
        articleCss.includes('aspect-ratio:16/9'),
        'src/views/BlogArticle.css must specify aspect-ratio: 16 / 9 to guarantee CLS = 0.00'
      );
    }
  });

  return results;
}
